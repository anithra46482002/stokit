def live_counts():
    envmap = {}
    for line in (ROOT / "django_backend" / ".env").read_text(encoding="utf-8-sig").splitlines():
        m = re.match(r"\s*(DB_[A-Z]+)\s*=\s*(.*)$", line)
        if m:
            envmap[m.group(1)] = m.group(2).strip()
    env = dict(os.environ, MYSQL_PWD=envmap["DB_PASSWORD"])
    base = [str(BIN), "-h", envmap["DB_HOST"], "-P", envmap["DB_PORT"], "-u", envmap["DB_USER"], "-D", envmap["DB_NAME"], "--batch", "--skip-column-names"]
    names = subprocess.run(base + ["-e", "select table_name from information_schema.tables where table_schema=database() and table_type='BASE TABLE' order by 1"], capture_output=True, text=True, env=env).stdout.split()
    sql = "SET SESSION TRANSACTION READ ONLY; " + " union all ".join("select '%s', count(*) from `%s`" % (n, n) for n in names)
    out = subprocess.run(base + ["-e", sql], capture_output=True, text=True, env=env).stdout
    now = subprocess.run(base + ["-e", "select now()"], capture_output=True, text=True, env=env).stdout.strip()
    return {a: int(b) for a, b in (ln.split("\t") for ln in out.splitlines() if ln)}, now


def tiers(tables):
    deps = {t: [p for p in FK.get(t, []) if p in tables] for t in tables}
    order, done, level = {}, set(), 0
    while len(done) < len(tables):
        ready = sorted(t for t in tables if t not in done and all(p in done for p in deps[t]))
        if not ready:
            raise SystemExit("FK cycle")
        for t in ready:
            order[t] = level
        done |= set(ready)
        level += 1
    return order


def main():
    counts, snap = live_counts()
    dump_parse = json.loads((DOCS / "STOKIT_DUMP_PARSER_VALIDATION_READONLY.json").read_text(encoding="utf-8"))
    dump_rows = {}
    for s in dump_parse["per_statement_counts"]:
        dump_rows[s["table"]] = dump_rows.get(s["table"], 0) + s["tuple_count"]
    diff = json.loads((DOCS / "STOKIT_SOURCE_COLUMN_DIFF_READONLY.json").read_text(encoding="utf-8"))["tables"]
    in_dump_schema = {t for t, v in T.items() if v[0] not in (D, A, X)}  # 45 legacy-dump tables
    in_dump_schema -= {"admin_cart_discount_settings"}
    missing = set(counts) - set(T)
    if missing:
        raise SystemExit("unclassified live tables: %s" % sorted(missing))
    tier = tiers([t for t in T if t != "django_migrations"])
    rows, recon = [], []
    for t in sorted(T):
        g, model, used = T[t]
        live = counts.get(t)
        dr = dump_rows.get(t, 0) if t in in_dump_schema else None
        d = diff.get(t, {})
        if t in in_dump_schema:
            if d:
                sh, do, lo, idn = d.get("shared"), d.get("dump_only"), d.get("live_only"), d.get("identical_rows")
            else:
                sh = do = lo = idn = 0
            if d and (d.get("dump_rows") != dr):
                raise SystemExit("dump row mismatch for " + t)
            mod = (sh or 0) - (idn or 0)
            if do == 0 and lo == 0 and mod == 0: cls = "IDENTICAL"
            elif do and not lo: cls = "DUMP SUPERSET" + (" + %d modified" % mod if mod else "")
            elif lo and not do: cls = "LIVE SUPERSET" + (" + %d modified" % mod if mod else "")
            else: cls = "DIVERGED" + (" (%d modified)" % mod if mod else "")
            if t in ("zg_slider",): cls = "DIVERGED"
            recon.append((t, dr, live, sh, do, lo, mod, cls))
        else:
            sh = do = lo = mod = None; cls = "NOT IN DUMP"
        rows.append({"table": t, "group": g, "model_or_access": model, "used_by": used, "dump_rows": dr, "live_rows": live,
                     "pg_exists": t in ("admin_cart_discount_settings", "django_migrations", "admins"), "load_tier": tier.get(t),
                     "shared_pk": sh, "dump_only": do, "live_only": lo, "modified_shared": mod, "classification": cls})
    (DOCS / "STOKIT_POSTGRESQL_TABLE_MANIFEST_READONLY.json").write_text(json.dumps({"live_snapshot_db_time": snap, "tables": rows}, indent=1), encoding="utf-8")

    frag = {}
    frag["MANIFEST"] = "| Table | Group | Django model / access | Used by | Dump rows | Live rows | PG now | Load tier |\n|---|---|---|---|---:|---:|---|---:|\n" + "\n".join(
        "| `%s` | %s | %s | %s | %s | %s | %s | %s |" % (r["table"], r["group"], r["model_or_access"], r["used_by"], "n/a" if r["dump_rows"] is None else r["dump_rows"], r["live_rows"] if r["live_rows"] is not None else "absent",
                                                       "exists" if r["pg_exists"] else "missing", "post-migrate" if r["load_tier"] is None else r["load_tier"]) for r in rows)
    frag["RECON"] = "| Table | Dump | Live | Shared PK | Dump-only | Live-only | Shared rows differing | Classification |\n|---|---:|---:|---:|---:|---:|---:|---|\n" + "\n".join(
        "| `%s` | %s | %s | %s | %s | %s | %s | %s |" % x for x in recon)
    frag["SNAPSHOT"] = snap
    by_tier = {}
    for r in rows:
        if r["load_tier"] is not None:
            by_tier.setdefault(r["load_tier"], []).append(r["table"])
    frag["LOADORDER"] = "\n".join("- **Tier %d:** %s" % (k, ", ".join("`%s`" % x for x in v)) for k, v in sorted(by_tier.items()))
    tot = {"identical": sum(1 for x in recon if x[7] == "IDENTICAL"), "n": len(recon)}
    frag["RECONTOTALS"] = "%d of %d dump-schema tables are fully identical (rows and content); %d differ." % (tot["identical"], tot["n"], tot["n"] - tot["identical"])
    for f in ("STOKIT_DATABASE_INVENTORY.md", "STOKIT_DATABASE_SOURCE_DECISION.md", "STOKIT_POSTGRESQL_SCHEMA_PLAN.md", "STOKIT_POSTGRESQL_MIGRATION_RUNBOOK.md", "STOKIT_POSTGRESQL_CUTOVER_CHECKLIST.md", "STOKIT_CART_DISCOUNT_ROOT_CAUSE.md"):
        p = DOCS / f
        if not p.exists():
            continue
        text = p.read_text(encoding="utf-8")
        for k, v in frag.items():
            text = text.replace("<!--@%s-->" % k, v)
        p.write_text(text, encoding="utf-8")
    print(json.dumps({"snapshot": snap, "tables": len(rows), "recon": frag["RECONTOTALS"], "tiers": {k: len(v) for k, v in by_tier.items()}}))


if __name__ == "__main__":
    main()

