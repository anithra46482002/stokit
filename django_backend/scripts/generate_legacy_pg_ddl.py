#!/usr/bin/env python3
"""Generate executable PostgreSQL DDL for the approved legacy StokIt tables.

Reads the MariaDB schema-only extract (create_tables.sql, alters.sql) and the reviewed inventory
manifest. Writes one SQL file. Never connects to any database and never reads row data.
Scope = inventory classification PROPOSED_PENDING_EVIDENCE minus tables that already exist
in the target (admins). Excluded tables are never emitted.
"""
import json
import pathlib
import re
import sys

SRC = pathlib.Path(r"C:\Users\.MSI\Downloads\stokit_sql_work\schema_extract")
DOCS = pathlib.Path(__file__).resolve().parents[1] / "docs"
INVENTORY = DOCS / "STOKIT_COMPLETE_POSTGRESQL_SCHEMA_INVENTORY.json"
OUT = DOCS / "STOKIT_COMPLETE_DDL_CANDIDATE.sql"
EXISTING_IN_TARGET = {"admins"}


def q(name):
    return '"' + name.replace('"', '""') + '"'


def ident_ok(name):
    assert len(name) <= 63, "identifier too long: " + name
    return name


def parse_creates(text):
    tables = {}
    for m in re.finditer(r"CREATE TABLE `(\w+)` \((.*?)\n\) ENGINE=", text, re.S):
        cols = []
        for line in m.group(2).split("\n"):
            line = line.rstrip().rstrip(",")
            cm = re.match(r"\s+`([^`]+)`\s+(.*)$", line)
            if cm:
                cols.append((cm.group(1), cm.group(2)))
        tables[m.group(1)] = cols
    return tables


def parse_alters(text):
    pk, uniq, keys, fks, autoinc = {}, {}, {}, {}, set()
    for stmt in re.finditer(r"ALTER TABLE `(\w+)`\n(.*?);", text, re.S):
        table, body = stmt.group(1), stmt.group(2)
        for clause in re.split(r",\s*\n\s*(?=ADD|MODIFY)", body.strip()):
            clause = clause.strip()
            cols = lambda s: re.findall(r"`([^`]+)`(?:\((\d+)\))?", s)
            m = re.match(r"ADD PRIMARY KEY \((.*)\)$", clause)
            if m:
                pk[table] = [c for c, _ in cols(m.group(1))]
                continue
            m = re.match(r"ADD UNIQUE KEY `(\w+)` \((.*)\)$", clause)
            if m:
                uniq.setdefault(table, []).append((m.group(1), [c for c, _ in cols(m.group(2))]))
                continue
            m = re.match(r"ADD KEY `(\w+)` \((.*)\)$", clause)
            if m:
                keys.setdefault(table, []).append((m.group(1), [c for c, _ in cols(m.group(2))]))
                continue
            m = re.match(r"MODIFY `(\w+)` .*AUTO_INCREMENT", clause)
            if m:
                autoinc.add((table, m.group(1)))
                continue
            m = re.match(r"ADD CONSTRAINT `(\w+)` FOREIGN KEY \(`(\w+)`\) REFERENCES `(\w+)` \(`(\w+)`\)( ON DELETE (CASCADE|SET NULL|RESTRICT))?$", clause)
            if m:
                fks.setdefault(table, []).append((m.group(1), m.group(2), m.group(3), m.group(4), m.group(6)))
                continue
            raise SystemExit("UNPARSED ALTER CLAUSE on %s: %s" % (table, clause))
    return pk, uniq, keys, fks, autoinc


def convert_column(table, name, spec, identity):
    tm = re.match(r"(enum\([^)]*\)|\w+(?:\([\d,]+\))?)(.*)$", spec)
    src_type, rest = tm.group(1), tm.group(2)
    rest = re.sub(r"\s*COMMENT\s+'(?:[^']|'')*'", "", rest)
    json_check = "json_valid" in rest
    rest = re.sub(r"\s*CHECK \(.*\)\s*$", "", rest)
    rest = re.sub(r"CHARACTER SET \w+|COLLATE \w+", "", rest)
    not_null = "NOT NULL" in rest
    dm = re.search(r"DEFAULT\s+('(?:[^']|'')*'|[\w.()+-]+)", rest)
    default = dm.group(1) if dm else None
    on_update = "ON UPDATE" in rest
    checks = []
    st = src_type.lower()
    if st.startswith("enum("):
        labels = re.findall(r"'((?:[^']|'')*)'", src_type)
        pg = "varchar(%d)" % max(len(x) for x in labels)
        checks.append(("ck_%s_%s" % (table, name), '%s IN (%s)' % (q(name), ", ".join("'%s'" % x for x in labels))))
    elif st == "tinyint(1)":
        pg = "boolean"
        if default is not None and default.upper() != "NULL":
            default = {"0": "FALSE", "1": "TRUE"}[default]
    elif st.startswith(("int", "integer")):
        pg = "integer"
    elif st.startswith("varchar"):
        pg = src_type
    elif st in ("text", "longtext"):
        pg = "text"
    elif st.startswith("decimal"):
        pg = src_type.replace("decimal", "numeric")
    elif st == "date":
        pg = "date"
    elif st in ("datetime", "timestamp"):
        pg = "timestamp"
    else:
        raise SystemExit("UNMAPPED TYPE %s.%s %s" % (table, name, src_type))
    if default is not None and default.upper() == "NULL":
        default = None
    if default is not None and default.lower().startswith("current_timestamp"):
        default = "CURRENT_TIMESTAMP"
    if json_check:
        checks.append(("ck_%s_%s_json" % (table, name), "%s IS NULL OR pg_input_is_valid(%s, 'jsonb')" % (q(name), q(name))))
    sql = "%s %s" % (q(name), pg)
    if identity:
        sql = "%s integer NOT NULL GENERATED BY DEFAULT AS IDENTITY" % q(name)
    else:
        if not_null:
            sql += " NOT NULL"
        if default is not None:
            sql += " DEFAULT " + default
    return sql, checks, on_update, pg


def main():
    inv = json.loads(INVENTORY.read_text(encoding="utf-8-sig"))
    scope = [t["name"] for t in inv["tables"] if t["classification"] == "PROPOSED_PENDING_EVIDENCE"]
    scope = sorted(t for t in scope if t not in EXISTING_IN_TARGET)
    excluded = sorted(t["name"] for t in inv["tables"] if t["classification"] != "PROPOSED_PENDING_EVIDENCE")
    creates = parse_creates((SRC / "create_tables.sql").read_text(encoding="utf-8-sig"))
    pk, uniq, keys, fks, autoinc = parse_alters((SRC / "alters.sql").read_text(encoding="utf-8-sig"))
    missing = [t for t in scope if t not in creates]
    if missing:
        raise SystemExit("scope tables missing from extract: %s" % missing)

    out = []
    stats = dict(tables=0, columns=0, pk=0, unique=0, ci_unique=0, indexes=0, fks=0, checks=0, updated_at_triggers=0)
    out.append("-- STOKIT COMPLETE DDL CANDIDATE (executable) - generated by scripts/generate_legacy_pg_ddl.py")
    out.append("-- Target: PostgreSQL 18, schema public. Structure only; no data. Scope: %d legacy tables (admins already exists and is not touched)." % len(scope))
    out.append("-- Excluded (%d, not emitted): %s" % (len(excluded), ", ".join(excluded)))
    out.append("-- Apply only with: psql -1 -v ON_ERROR_STOP=1 -f <this file>  (single transaction, aborts on first error).")
    out.append("")
    on_update_tables = []
    for t in scope:
        defs, checks = [], []
        for name, spec in creates[t]:
            sql, ck, on_upd, _pg = convert_column(t, name, spec, (t, name) in autoinc)
            defs.append("  " + sql)
            checks += ck
            stats["columns"] += 1
            if on_upd:
                on_update_tables.append((t, name))
        if t in pk:
            defs.append("  CONSTRAINT %s PRIMARY KEY (%s)" % (q(ident_ok("pk_" + t)), ", ".join(q(c) for c in pk[t])))
            stats["pk"] += 1
        for cname, expr in checks:
            defs.append("  CONSTRAINT %s CHECK (%s)" % (q(ident_ok(cname)), expr))
            stats["checks"] += 1
        out.append("CREATE TABLE public.%s (\n%s\n);" % (q(t), ",\n".join(defs)))
        out.append("")
        stats["tables"] += 1

    varchar_cols = {}
    for t in scope:
        for name, spec in creates[t]:
            if spec.lower().startswith("varchar"):
                varchar_cols.setdefault(t, set()).add(name)

    for t in scope:
        for kname, cols in uniq.get(t, []):
            out.append("ALTER TABLE public.%s ADD CONSTRAINT %s UNIQUE (%s);" % (q(t), q(ident_ok("uq_%s_%s" % (t, kname))), ", ".join(q(c) for c in cols)))
            stats["unique"] += 1
            if any(c in varchar_cols.get(t, ()) for c in cols):
                exprs = ["lower(%s)" % q(c) if c in varchar_cols[t] else q(c) for c in cols]
                out.append("CREATE UNIQUE INDEX %s ON public.%s (%s);" % (q(ident_ok("uqci_%s_%s" % (t, kname))), q(t), ", ".join(exprs)))
                stats["ci_unique"] += 1
        for kname, cols in keys.get(t, []):
            out.append("CREATE INDEX %s ON public.%s (%s);" % (q(ident_ok("ix_%s_%s" % (t, kname))), q(t), ", ".join(q(c) for c in cols)))
            stats["indexes"] += 1
    out.append("")
    for t in scope:
        for cname, col, rt, rc, ondel in fks.get(t, []):
            if rt not in scope and rt not in EXISTING_IN_TARGET:
                out.append("-- SKIPPED FK %s.%s -> %s (referenced table not in scope)" % (t, cname, rt))
                continue
            out.append("ALTER TABLE public.%s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES public.%s (%s)%s;" % (
                q(t), q(cname), q(col), q(rt), q(rc), (" ON DELETE " + ondel) if ondel else ""))
            stats["fks"] += 1
    out.append("")
    out.append("-- ON UPDATE CURRENT_TIMESTAMP emulation (MariaDB bumps the column only when another column changed")
    out.append("-- and the statement did not set the column itself).")
    out.append("""CREATE FUNCTION public.stokit_set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at AND ROW(NEW.*) IS DISTINCT FROM ROW(OLD.*) THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;
    RETURN NEW;
END
$fn$;""")
    for t, col in on_update_tables:
        assert col == "updated_at", (t, col)
        out.append("CREATE TRIGGER %s BEFORE UPDATE ON public.%s FOR EACH ROW EXECUTE FUNCTION public.stokit_set_updated_at();" % (q(ident_ok("trg_%s_set_updated_at" % t)), q(t)))
        stats["updated_at_triggers"] += 1
    out.append("")
    out.append("""-- Port of MariaDB trigger update_target_progress_after_order. MariaDB evaluates SET assignments left to right
-- (later ones see earlier results); here amount/count are computed first so status/achieved_date use the new amount.
-- Comparisons on email/status use lower() to keep MariaDB case-insensitive collation behaviour.
CREATE FUNCTION public.update_target_progress_after_order() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
    WITH s AS (
        SELECT ta.assignment_id, t.target_amount,
               COALESCE((SELECT SUM(oi.total_price)
                         FROM zg_order_items oi
                         JOIN zg_product p ON oi.product_id = p.product_id
                         WHERE p.category_id = t.category_id
                           AND oi.order_id IN (SELECT c.order_id FROM zg_checkout c
                                               WHERE lower(c.email) = lower(u.email)
                                                 AND lower(c.status) = 'fulfilled'
                                                 AND c.order_date BETWEEN t.start_date AND t.end_date + 1)), 0) AS amount,
               (SELECT COUNT(DISTINCT oi.order_id)
                FROM zg_order_items oi
                JOIN zg_product p ON oi.product_id = p.product_id
                WHERE p.category_id = t.category_id
                  AND oi.order_id IN (SELECT c.order_id FROM zg_checkout c
                                      WHERE lower(c.email) = lower(u.email)
                                        AND lower(c.status) = 'fulfilled'
                                        AND c.order_date BETWEEN t.start_date AND t.end_date + 1)) AS cnt
        FROM zg_target_assignments ta
        JOIN zg_targets t ON ta.target_id = t.target_id
        JOIN users u ON u.id = ta.user_id
        WHERE t.status = 'ACTIVE' AND lower(u.email) = lower(NEW.email)
    )
    UPDATE zg_target_assignments ta
    SET achieved_amount = s.amount,
        order_count = s.cnt,
        status = CASE WHEN s.amount >= s.target_amount THEN 'ACHIEVED' ELSE 'PENDING' END,
        achieved_date = CASE WHEN s.amount >= s.target_amount THEN CURRENT_DATE ELSE ta.achieved_date END,
        updated_at = CURRENT_TIMESTAMP
    FROM s
    WHERE ta.assignment_id = s.assignment_id;
    RETURN NULL;
END
$fn$;
CREATE TRIGGER update_target_progress_after_order AFTER UPDATE ON public.zg_checkout
    FOR EACH ROW WHEN (lower(NEW.status) = 'fulfilled' AND lower(OLD.status) <> 'fulfilled')
    EXECUTE FUNCTION public.update_target_progress_after_order();""")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(json.dumps(dict(stats, scope_tables=len(scope), excluded=len(excluded), output=str(OUT))))


if __name__ == "__main__":
    sys.exit(main())
